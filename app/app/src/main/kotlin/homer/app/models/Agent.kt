@Serializable
data class Agent(
    val name: String,
    val description: String? = null,
    /** Optional operator-facing label; the console's Agents page renders one tab per distinct group. */
    val group: String? = null,
    val workspace: Workspace = Workspace(),
    val commands: List<Command>,
    val env: Map<String, String> = emptyMap(),
    val inputs: List<Param>? = null,
    @Deprecated("Use 'inputs' instead", ReplaceWith("inputs"))
    val queryParams: List<Param>? = null,
    val lockStrategy: LockStrategy = LockStrategy(),
    val cron: CronConfig? = null,
    val maxParallelRuns: Int = 10,
    val onMaxParallelRuns: OnMaxParallelRunsStrategy = OnMaxParallelRunsStrategy.WAIT,
    // Under `onMaxParallelRuns: WAIT`, the maximum number of runs that may be
    // queued (suspended) waiting for a parallel-run slot. Null = unbounded (the
    // default; a surplus run waits indefinitely). A non-null value fails the
    // surplus run once the queue is full, bounding the non-evictable process
    // rows a single agent can pin. No effect under `REJECT` (already fails fast).
    val maxQueuedRuns: Int? = null,
    /**
     * Runner alias this agent runs on. Null = `local`. Mutually exclusive with
     * [runnerTags]. See ADR-0066.
     */
    val runner: String? = null,
    /** Tags a runner must serve to take this agent's runs; empty = select by [runner]. See ADR-0066. */
    val runnerTags: List<String> = emptyList(),
    /** Seconds to wait for a runner to claim a run; null = `server.runnerClaimTimeoutSec`. */
    val runnerClaimTimeoutSec: Int? = null,
    // Optional JSON Schema (Draft 2020-12) validating the JSON request body of
    // POST /api/v1/agent/{name}. Null = no payload validation. A malformed schema
    // causes the agent to be skipped at load (AgentsService). Validation happens
    // in AgentInputResolver before the process is spawned; a violation → 422.
    @Serializable(with = JsonObjectSerializer::class)
    val inputSchema: JsonObject? = null,
    // Opt-in exposure of this agent as an MCP tool on the /mcp endpoint
    // (requires server.mcp.enabled). Null or enabled=false = not exposed.
    val mcp: AgentMcpConfig? = null,
    // Opt-in: may this agent be the TARGET of an ask-and-dispatch dispatch?
    // Null or enabled=false = cannot be dispatched. See the ask-and-dispatch ADR.
    val dispatch: AgentDispatchConfig? = null,
    /** How this agent's runs appear in the OTel collector. See [AgentTelemetry]. */
    val telemetry: AgentTelemetry = AgentTelemetry(),
    /** The run's subject tags: what it runs over, and how they are declared. See [Tags]. */
    val tags: Tags = Tags(),
    /**
     * Optional minimum spacing between runs of this agent. Null = no limit.
     * Enforced at every start path that goes through `AgentRunStarter`.
     */
    val cooldown: Cooldown? = null,
    /**
     * Template for the *stem* of the autogenerated per-command stdout/stderr
     * artifact files (Homer appends `.out`/`.err`). Rendered per command and per
     * attempt by `ArtifactNameResolver` — see AGENT.md's "Template-only Variables" /
     * Agent Fields sections. The default renders the same path on every attempt,
     * so it truncates in place exactly as before this field existed.
     */
    val artifactNameTemplate: String = EnvConstants.DEFAULT_ARTIFACT_NAME_TEMPLATE,
    // Runtime-only: reflects whether the on-disk agent directory is writable.
    // Not serialized to/from disk; populated by AgentsService at scan time and
    // surfaced via AgentInfo on the API.
    @Transient
    val writable: Boolean = true,
    /**
     * Runtime-only: names to redact for this agent's `env` — the keys whose
     * *raw* value referenced `@SYSENV:`, plus the host variables they referenced
     * (a composite like `"Bearer @SYSENV:TOKEN"` needs both). Not serialized;
     * populated by AgentsService at scan time and unioned into the run's
     * redacted-value set, since a value pulled from the host env is by
     * construction a secret. See `SysEnvResolver.secretNamesFor`.
     */
    @Transient
    val sysEnvBackedEnvNames: Set<String> = emptySet(),
) {
    init {
        // Reads the legacy alias on purpose: an agent may set only one of the two forms.
        @Suppress("DEPRECATION")
        require(inputs == null || queryParams == null) {
            "Agent '$name': set either 'inputs' or legacy 'queryParams', not both"
        }
        require(maxQueuedRuns == null || maxQueuedRuns >= 0) {
            "Agent '$name': maxQueuedRuns must be >= 0 (or null for unbounded), got $maxQueuedRuns"
        }
        require(runner == null || runnerTags.isEmpty()) {
            "Agent '$name': runner and runnerTags are mutually exclusive"
        }
        require(runner == null || runner.isNotBlank()) { "Agent '$name': runner must not be blank" }
        RunnerTagValidation.validate("Agent '$name'", runnerTags)
        AgentGroupValidation.validate("Agent '$name'", group)
        require(runnerClaimTimeoutSec == null || runnerClaimTimeoutSec >= 1) {
            "Agent '$name': runnerClaimTimeoutSec must be >= 1 when set, got $runnerClaimTimeoutSec"
        }
    }

    // Reads the legacy alias on purpose: it is the fallback for agents still using it.
    @Transient
    @Suppress("DEPRECATION")
    val effectiveInputs: List<Param>? = inputs ?: queryParams

    /** The claim-queue filter this agent's runs wait on. See ADR-0066. */
    @Transient
    val runnerFilter: RunnerFilter =
        if (runnerTags.isNotEmpty()) RunnerFilter.Tags(runnerTags.toSet()) else RunnerFilter.Alias(runner ?: "local")

    /**
     * envNames of the inputs declared `secret: true` **right now**. For a run that
     * replays stored inputs (retry, resume) this is not enough on its own — the
     * definition may have been edited since — so those paths union it with the
     * source run's snapshot. See ADR-0052.
     */
    @Transient
    val secretEnvNames: Set<String> =
        effectiveInputs
            .orEmpty()
            .filter { it.secret }
            .map { it.envName }
            .toSet()

    /**
     * paramNames of the inputs declared `secret: true` **right now** — the paramName
     * counterpart of [secretEnvNames]. Dispatch/continuation registration snapshots this
     * alongside [secretEnvNames] because their stored `params` map is paramName-keyed,
     * not envName-keyed; see `redactStoredParams` and ADR-0052.
     */
    @Transient
    val secretParamNames: Set<String> =
        effectiveInputs
            .orEmpty()
            .filter { it.secret }
            .map { it.paramName }
            .toSet()

    /**
     * The effective `fromInputs` tag sources: `tags.fromInputs` unioned with the
     * deprecated `telemetry.traceTags` alias (order-preserving, de-duplicated).
     * This single list feeds both the Langfuse trace tags and the process-tag rows,
     * so the two never diverge. See ADR-0050 and ADR-0060.
     */
    @Transient
    @Suppress("DEPRECATION")
    val effectiveFromInputTags: List<String> =
        (tags.fromInputs + telemetry.traceTags).distinct()
}

/**
 * Minimum spacing between runs of one agent — the frequency bound `lockStrategy`
 * (concurrency) and `costLimits` (spend) do not provide. Durations use the
 * `purgeAfter` grammar: `30s` is not valid, use `1m` / `2h` / `1d` / `1w`.
 *
 * Both fields are optional but at least one must be set — an empty block would
 * silently do nothing, which is worse than a load error.
 */
@Serializable
data class Cooldown(
    /** Minimum time since the previous run of this agent *started*. */
    val minInterval: String? = null,
    /**
     * Minimum time since the previous run *ended*, applied only when that run
     * FAILED. Backs off a failing agent without slowing down a healthy one — the
     * shape a frequently-scheduled watcher needs.
     */
    val afterFailure: String? = null,
) {
    init {
        require(minInterval != null || afterFailure != null) {
            "cooldown must set minInterval, afterFailure, or both"
        }
        minInterval?.let { PurgeAfterParser.toSeconds(it, "cooldown.minInterval") }
        afterFailure?.let { PurgeAfterParser.toSeconds(it, "cooldown.afterFailure") }
    }

    val minIntervalSeconds: Long? get() = minInterval?.let { PurgeAfterParser.toSeconds(it, "cooldown.minInterval") }

    val afterFailureSeconds: Long? get() = afterFailure?.let { PurgeAfterParser.toSeconds(it, "cooldown.afterFailure") }
}

/**
 * Everything this agent decides about its own telemetry, in one place. Server-wide
 * export (`openTelemetryExport`) still gates all of it. See ADR-0050.
 */
@Serializable
data class AgentTelemetry(
    val export: TelemetryExport = TelemetryExport.ALL,
    /**
     * `paramName`s of declared inputs whose resolved values become `paramName:value`
     * tags on the run's trace, so a run is findable by what it is about (ticket, MR,
     * thread) — the Langfuse traces API filters on tags, and cannot see span
     * attributes. Every name must match a declared input, and must not name a
     * `secret` input; both are checked at agent load.
     */
    @Deprecated("Use the top-level 'tags.fromInputs' block instead", ReplaceWith("tags.fromInputs"))
    val traceTags: List<String> = emptyList(),
)

/**
 * A run's subject tags — what it ran over — so it is findable by
 * `GET /api/v1/status/all?tag=key:value`. Two declaration styles, unioned into
 * the run's tag set:
 *
 * - [fromInputs] names declared inputs by `paramName`; each resolved value becomes
 *   a `paramName:value` tag at start, reusing the trace-tag derivation. This is the
 *   modern home of the deprecated `telemetry.traceTags`, so a tag is both a trace
 *   tag and a queryable run tag from one declaration.
 * - [runtime] names keys a running command may declare later via the `homer-tag`
 *   helper (`POST /api/v1/callback/tags`) — for facts not known until the run has
 *   started. A `runtime` key must be disjoint from a `fromInputs` name; overlap is
 *   a load error.
 *
 * See ADR-0060.
 */
@Serializable
data class Tags(
    val fromInputs: List<String> = emptyList(),
    val runtime: List<String> = emptyList(),
)

/** Whether an agent's runs reach the collector at all. See [AgentTelemetry.export]. */
@Serializable
enum class TelemetryExport {
    /** Export this agent's runs (default). */
    ALL,

    /** Export nothing for this agent's runs — the whole trace, not just the root span. */
    OFF,
}

