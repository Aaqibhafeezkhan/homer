/**
 * Conditional execution predicate. A non-null `whenClause` on a Command gates
 * its execution: each expression is evaluated as `bash -c <expr>` against the
 * command's env (post-transformation), with `cwd = workspace.workdir`.
 *
 * Exit code semantics per expression: 0 = true, 1 = false, ≥ 2 = eval error
 * (fails the agent — surfaces predicate bugs instead of silently skipping).
 *
 * `ALL` is AND (short-circuits on first false); `ANY` is OR (short-circuits on
 * first true). Per-expression timeout is 5 s (not configurable in v1).
 *
 * Wire format accepts a string shorthand (treated as `{all: [<string>]}`),
 * `{all: [...]}`, or `{any: [...]}`. See `WhenSerializer`.
 */
@Serializable(with = WhenSerializer::class)
data class When(
    val operator: Operator,
    val expressions: List<String>,
) {
    enum class Operator { ALL, ANY }

    init {
        require(expressions.isNotEmpty()) { "when must have at least one expression" }
        require(expressions.all { it.isNotBlank() }) { "when expressions must be non-blank" }
    }
}

